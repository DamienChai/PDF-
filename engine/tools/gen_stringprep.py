#!/usr/bin/env python3
"""Generates src/engine/stringprep-data.ts from the RFC 3454 tables in Python's stdlib.

    python3 engine/tools/gen_stringprep.py

The tables are frozen (stringprep is defined on Unicode 3.2), so this only needs to be re-run if
the encoding of the generated file changes.
"""
import pathlib
import stringprep

MAX = 0x110000
DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"


def base36(n: int) -> str:
    out = ""
    while True:
        n, d = divmod(n, 36)
        out = DIGITS[d] + out
        if n == 0:
            return out


def ranges(predicate):
    """Inclusive [start, end] ranges of the code points for which predicate holds."""
    result = []
    start = None
    for cp in range(MAX):
        if predicate(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            result.append((start, cp - 1))
            start = None
    if start is not None:
        result.append((start, MAX - 1))
    return result


def pack(rs) -> str:
    """Delta encoding: for each range, the gap from the previous end and the length - 1, base 36."""
    parts = []
    prev = 0
    for start, end in rs:
        parts.append(base36(start - prev))
        parts.append(base36(end - start))
        prev = end
    return ",".join(parts)


def any_of(*tables):
    return lambda ch: any(t(ch) for t in tables)


TABLES = {
    # B.1: commonly mapped to nothing
    "MAP_TO_NOTHING": stringprep.in_table_b1,
    # C.1.2: non-ASCII space characters (mapped to U+0020 by SASLprep)
    "NON_ASCII_SPACE": stringprep.in_table_c12,
    # C.2.1 C.2.2 C.3 C.4 C.5 C.6 C.7 C.8 C.9 (C.1.2 is covered by NON_ASCII_SPACE)
    "PROHIBITED": any_of(
        stringprep.in_table_c21,
        stringprep.in_table_c22,
        stringprep.in_table_c3,
        stringprep.in_table_c4,
        stringprep.in_table_c5,
        stringprep.in_table_c6,
        stringprep.in_table_c7,
        stringprep.in_table_c8,
        stringprep.in_table_c9,
    ),
    # D.1: characters with bidirectional property R or AL
    "RAND_AL_CAT": stringprep.in_table_d1,
    # D.2: characters with bidirectional property L
    "L_CAT": stringprep.in_table_d2,
}

lines = [
    "// GENERATED by engine/tools/gen_stringprep.py from the RFC 3454 tables. Do not edit.",
    "//",
    "// Each table is a list of inclusive code point ranges, delta-encoded in base 36:",
    "// `gap,length-1,gap,length-1,...` where `gap` is the distance from the end of the previous",
    "// range (or from 0) to the start of this one.",
    "",
]
for name, predicate in TABLES.items():
    rs = ranges(predicate)
    lines.append(f"/** {len(rs)} ranges. */")
    packed = pack(rs)
    single = f"export const {name} = '{packed}';"
    if len(single) <= 100:  # the layout Prettier would choose
        lines.append(single)
    else:
        lines.append(f"export const {name} =")
        chunks = [packed[i : i + 92] for i in range(0, len(packed), 92)]
        for i, chunk in enumerate(chunks):
            end = ";" if i == len(chunks) - 1 else " +"
            lines.append(f"  '{chunk}'{end}")
    lines.append("")

out = pathlib.Path(__file__).resolve().parents[2] / "src" / "engine" / "stringprep-data.ts"
out.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size} bytes)")
