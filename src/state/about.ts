/** What the About section shows besides translated text. */
import { computed, type ReadonlySignal } from '@preact/signals';
// Named imports: only these values end up in the bundle, not the whole files.
import { version } from '../../package.json';
import { emscripten, jpeg, qpdf, zlib } from '../engine/dist/BUILDINFO.json';
import { engineState, type EngineStatus } from './engine';

/** Version of the app, from package.json. */
export const APP_VERSION: string = version;

export interface OpenSourceComponent {
  name: string;
  /** Empty when the version is not tracked here; the notices file names it. */
  version: string;
  /** SPDX licence expression, or the common name where there is none. */
  license: string;
}

/**
 * Third-party code that is part of what the app ships, in short: the engine's components and
 * the JavaScript libraries. Versions, origins and the licence texts are in the notices file.
 */
export const OPEN_SOURCE_COMPONENTS: readonly OpenSourceComponent[] = [
  { name: 'qpdf', version: qpdf, license: 'Apache-2.0' },
  { name: 'zlib', version: zlib, license: 'Zlib' },
  { name: 'libjpeg (IJG)', version: jpeg, license: 'IJG' },
  { name: 'Emscripten', version: emscripten, license: 'MIT OR NCSA' },
  { name: 'musl libc', version: '', license: 'MIT' },
  { name: 'LLVM libc++ / compiler-rt', version: '', license: 'Apache-2.0 WITH LLVM-exception' },
  { name: 'dlmalloc', version: '', license: 'CC0-1.0' },
  { name: 'Preact', version: '', license: 'MIT' },
  { name: 'Preact Signals', version: '', license: 'MIT' },
  { name: 'Workbox', version: '', license: 'MIT' },
  { name: 'Vite / Rolldown', version: '', license: 'MIT' },
];

/**
 * The notices file every build ships next to index.html: copyright notices and licence texts of
 * all of the above. Generated by scripts/third-party-notices.ts, which repeats the name.
 */
export const THIRD_PARTY_NOTICES_URL = './licenses.txt';

export interface AboutInfo {
  appVersion: string;
  engineStatus: EngineStatus;
  /** Version of the qpdf library inside the engine; null until the engine is loaded. */
  qpdfVersion: string | null;
  /** The engine runs on the main thread because workers are unavailable (slower, may stutter). */
  compatibilityMode: boolean;
}

export const aboutInfo: ReadonlySignal<AboutInfo> = computed(() => ({
  appVersion: APP_VERSION,
  engineStatus: engineState.status.value,
  qpdfVersion: engineState.info.value?.qpdfVersion ?? null,
  compatibilityMode: engineState.info.value?.mode === 'main-thread',
}));
